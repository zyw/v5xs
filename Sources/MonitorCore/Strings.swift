    public static func current(_ key: StringKey) -> String {
        text(key, Localization.shared.language)
    }

    /// 按当前界面语言取带参数文案。
    public static func current(_ key: StringKey, _ args: CVarArg...) -> String {
        String(format: text(key, Localization.shared.language), arguments: args)
    }

    public static func text(_ key: StringKey, _ language: AppLanguage) -> String {
        let table: [StringKey: String]
        switch language {
        case .zhHans: table = hans
        case .zhHant: table = hant
        case .en: table = en
        }
        return table[key] ?? hans[key] ?? key.rawValue
    }

